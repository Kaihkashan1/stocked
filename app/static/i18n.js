const LANGUAGE_KEY = "recipeBox.language";

function languagePreference() {
  return localStorage.getItem(LANGUAGE_KEY) || "system";
}

function setLanguagePreference(value) {
  localStorage.setItem(LANGUAGE_KEY, value);
}

function appLocale() {
  const pref = languagePreference();
  if (pref === "de" || pref === "en") return pref;
  const lang = (navigator.language || "en").toLowerCase();
  return lang.startsWith("de") ? "de" : "en";
}

function t(key, vars) {
  const table = I18N[appLocale()] || {};
  let text = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : null;
  if (text == null) {
    const fallback = I18N.en || {};
    text = Object.prototype.hasOwnProperty.call(fallback, key) ? fallback[key] : key;
  }
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

// Only the six fixed suggested tags (RECIPE_TAGS, defined in app.js) have
// real translations — a free-text custom tag must never be looked up
// against the whole app-wide string table, or a tag that happens to match
// an unrelated UI key (e.g. "high", "notes", "close") would silently
// render as that unrelated translated string instead of the user's tag.
function tTag(tag) {
  if (typeof RECIPE_TAGS !== "undefined" && RECIPE_TAGS.includes(tag)) {
    return t(tag);
  }
  return tag;
}

function applyStaticI18n() {
  document.documentElement.lang = appLocale() === "de" ? "de" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  const title = document.querySelector("title");
  if (title) title.textContent = t("recipeBox");
}
